//   - open marks (arrows, check, plus, slash, handle, bars) are 2px wide;
//   - each icon may carry one solid mass (a folder tab, an envelope flap, a lock body, a speaker) for weight,
//     as the early Mac icons did; the moon is solid so the dark-theme toggle reads at a glance.
// Each bitmap becomes one path per colour, a rect per horizontal run, drawn with crispEdges at 16px or 32px
