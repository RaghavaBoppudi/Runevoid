const runs = (rows, ch) => rows.flatMap((row, y) => [...row.matchAll(ch === '#' ? /#+/g : /o+/g)]
  .map((m) => `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`)).join('');

// Built once at startup: each icon is a ready-made SVG string, so rendering a page only concatenates.
const SVG = {};
for (const [name, rows] of Object.entries(BITMAPS)) {
  const fill = runs(rows, 'o');
  SVG[name] = `${fill ? `<path class="o" d="${fill}"/>` : ''}<path class="k" d="${runs(rows, '#')}"/>`;
}

export const icon = (name, cls = '') =>
  `<svg class="i${cls ? ` ${cls}` : ''}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${SVG[name] ?? ''}</svg>`;
